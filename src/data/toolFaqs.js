export function getToolFaq(slug, lang) {
    const tool = toolFaqs[slug];
    if (!tool) return null;
    return tool[lang] || tool.en || null;
}

export function buildToolFaqSchema(slug, lang) {
    const faq = getToolFaq(slug, lang);
    if (!faq || !faq.questions?.length) return null;

    return {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": faq.questions.map(item => ({
            "@type": "Question",
            "name": item.q,
            "acceptedAnswer": {
                "@type": "Answer",
                "text": item.a
            }
        }))
    };
}
